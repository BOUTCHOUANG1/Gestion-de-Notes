    public ReportResponse generateSubjectReport(Long subjectId, ReportRequest reportRequest) {
        ReportResponse response = new ReportResponse();
        try {
            var studentOpt = studentRepository.findById(reportRequest.getStudentId());
            var semesterOpt = semesterRepository.findById(reportRequest.getSemesterId());
            var subjectOpt = subjectRepository.findById(subjectId);
            if (studentOpt.isEmpty() || semesterOpt.isEmpty() || subjectOpt.isEmpty())
                throw new RuntimeException("Student/Semester/Subject not found");
            var student = studentOpt.get();
            var semester = semesterOpt.get();
            var subject = subjectOpt.get();

            List<Grades> grades = gradeRepository.findByStudentIdAndSubjectId(reportRequest.getStudentId(), subjectId);
            if (!grades.isEmpty()) {
                grades = grades.stream().filter(g -> g.getSemesters() != null && g.getSemesters().getId().equals(reportRequest.getSemesterId())).toList();
            }

            double gpa = 0;
            if (!grades.isEmpty()) {
                double total = grades.stream().mapToDouble(Grades::getValue).sum();
                gpa = Math.round((total / grades.size()) * 100.0) / 100.0;
            }

            // map grades
            java.util.List<com.university.ManageNotes.dto.Response.GradeResponse> gradeDtos = grades.stream().map(this::mapGrade).toList();
            response.setGrades(gradeDtos);

            int creditsEarned = grades.stream()
                    .filter(g -> g.getValue() >= 10)
                    .map(g -> g.getSubject().getCredits().intValue())
                    .reduce(0, Integer::sum);

            response.setStudentId(student.getId());
            response.setStudentName(student.getFirstName() + " " + student.getLastName());
            response.setSemesterId(semester.getId());
            response.setSemesterName(semester.getName());
            response.setSubjectId(subject.getId());
            response.setSubjectName(subject.getName());
            response.setGpa(gpa);
            response.setStatus(creditsEarned >= 55 ? "PROMOTED" : "RETAKE");
            response.setReportType("SUBJECT_GRADES");
            response.setCreatedDate(Instant.now());
            Users currentUser = authService.getCurrentUser();
            response.setGeneratedBy(currentUser.getId());
            response.setGeneratedByName(currentUser.getFirstName() + " " + currentUser.getLastName());

            // generate pdf
            byte[] pdf = generatePDFReport(student, grades, "Subject Report");
            Path dir = Paths.get("generated-reports");
            Files.createDirectories(dir);
            String fileName = "student_" + student.getId() + "_subject_" + subjectId + "_" + Instant.now().toEpochMilli() + ".pdf";
            Path filePath = dir.resolve(fileName);
            Files.write(filePath, pdf);
            response.setPdfPath(filePath.toString());
            response.setDownloadUrl("/files/" + fileName);
            response.setLastModifiedDate(response.getCreatedDate());

            try {
                emailService.sendMessageWithAttachment(
                        student.getEmail(),
                        "Subject Report",
                        "Dear Parent,\n\nAttached is the subject report for " + student.getFirstName() + " " + student.getLastName() + ".\n\nRegards", pdf, fileName);
            } catch (Exception ignored) {}

            // Persist record similar to student report
            ReportRecord record = new ReportRecord();
            record.setStudentId(response.getStudentId());
            record.setSemesterId(response.getSemesterId());
            record.setSubjectId(response.getSubjectId());
            record.setReportType(response.getReportType());
            record.setGpa(response.getGpa());
            record.setStatus(response.getStatus());
            record.setPdfPath(response.getPdfPath());
            record.setDownloadUrl(response.getDownloadUrl());
            record.setGeneratedBy(response.getGeneratedBy());
            record.setLastModifiedDate(response.getLastModifiedDate());
            ReportRecord saved = reportRecordRepository.save(record);
            reportRecordRepository.flush();
            response.setId(saved.getId());

            response.setSuccess(true);
            response.setMessage("Subject report generated successfully");
            return response;
        } catch (Exception e) {
            response.setSuccess(false);
            response.setMessage("Failed to generate subject report: " + e.getMessage());
            return response;
        }
    }

    public byte[] exportToExcel(List<Grades> grades) throws IOException {
        // Simulate Excel export
        StringBuilder csvContent = new StringBuilder();
        csvContent.append("Student,Subject,Grade,Type,Semester\n");

        for (Grades grade : grades) {
            csvContent.append(grade.getStudent().getFirstName()).append(" ").append(grade.getStudent().getLastName()).append(",");
            csvContent.append(grade.getSubject().getName()).append(",");
            csvContent.append(grade.getValue()).append(",");
            csvContent.append(grade.getGradeType().name()).append(",");
            csvContent.append(grade.getSemesters().getName()).append("\n");
        }

        return csvContent.toString().getBytes();
    }

    public ReportResponse getStudentYearSummary(Long studentId) {
        ReportRequest dummy = new ReportRequest();
        dummy.setStudentId(studentId);
        // we assume semesters table has at least two entries ordered
        var semesters = semesterRepository.findAll();
        if (semesters.size() >= 2) {
            dummy.setSemesterId(semesters.get(0).getId()); // any non-null to satisfy validation
        }
        dummy.setIncludePdf(false);
        return generateStudentReport(studentId, dummy);
    }
